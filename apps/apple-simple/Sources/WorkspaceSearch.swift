import SwiftUI
import Observation
@MainActor @Observable final class WorkspaceSearch {
    var query = "" { didSet { invalidate() } }
    var regex = false { didSet { invalidate() } }
    var matchCase = false { didSet { invalidate() } }
    var wholeWord = false { didSet { invalidate() } }
    var result: WorkspaceSearchResult?
    var notice = ""
    var page = 0
    var revision = UUID()
    func invalidate() { revision = UUID(); result = nil; notice = ""; page = 0 }
    func run(_ engine: Engine?) async {
        guard let engine, !query.isEmpty else { notice = "Connect to a workspace and enter a query."; return }
        revision = UUID(); let request = revision; result = nil; page = 0; notice = "Searching saved workspace text…"
        do { let answer = try await engine.find(query, regex: regex, matchCase: matchCase, wholeWord: wholeWord); if revision == request { result = answer; notice = "" } }
        catch { if revision == request { notice = "\(error.localizedDescription) Check the query and retry." } }
    }
}
struct WorkspaceSearchView: View {
    @Bindable var workspace: Workspace
    var body: some View {
        @Bindable var search = workspace.search
        let hits = search.result?.hits ?? [], last = max(0, (hits.count + 99) / 100 - 1), selected = min(search.page, last)
        VStack(alignment: .leading, spacing: 8) {
            HStack { Text("Find in workspace").font(.headline); Spacer(); Button("Close") { workspace.showWorkspaceSearch = false; search.revision = UUID(); workspace.currentBuffer?.focusSource?() } }
            Text("Saved workspace text · unsaved edits are preserved").font(.caption)
            TextField("Workspace search query", text: $search.query).textFieldStyle(.roundedBorder).onSubmit { Task { await search.run(workspace.engine) } }
            Toggle("Regular expression", isOn: $search.regex); Toggle("Match case", isOn: $search.matchCase); Toggle("Whole word", isOn: $search.wholeWord)
            Button("Search") { Task { await search.run(workspace.engine) } }.disabled(reason: search.query.isEmpty ? "Enter a search term." : nil)
            if !search.notice.isEmpty { Text(search.notice).font(.caption) }
            if let result = search.result { Text("\(hits.count) occurrences" + (result.truncated ? " · Result cap reached; narrow the query" : "")).font(.caption) }
            ScrollView { VStack(alignment: .leading, spacing: 6) {
                ForEach(Array(hits.dropFirst(selected * 100).prefix(100))) { hit in
                    Button("\(hit.path):\(hit.line) · \(hit.text)") { Task { await workspace.openSearchHit(hit) } }
                    if let owner = hit.generatedBy { Text("Generated by \(owner) · read-only").font(.caption) }
                }
            } }
            if last > 0 { HStack { Button("Previous results") { search.page = selected - 1 }.disabled(reason: selected == 0 ? "You’re on the first page." : nil); Text("\(selected + 1)/\(last + 1)"); Button("Next results") { search.page = selected + 1 }.disabled(reason: selected == last ? "You’re on the last page." : nil) } }
        }.padding(8).frame(width: 350, height: 440)
    }
}
