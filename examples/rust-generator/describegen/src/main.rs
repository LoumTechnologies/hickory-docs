//! The generator: three rules over the model, and nothing else.
//!
//! Everything it needs from the transport is in `hick_model.rs`, and
//! everything it needs from the schema is in `model.rs`. Both were emitted by
//! `hick code-model rust`, which is why this file is short enough to review —
//! and reviewing the generator instead of its output is the entire point of
//! `docs/specs/freeform/language-tiers.md`'s Gold rung.
//!
//!     describegen <model server> <workspace root>
//!
//! It writes to **stdout**. The document owns the bytes, through `hick:file`,
//! where lineage and the drift gate already work — which is why no model
//! server in this product is allowed to write.

mod hick_model;
mod model;

use hick_model::{Emit, Model, ModelError};
use model::{DescribedTypesTypesKind, described_types};

fn main() -> Result<(), ModelError> {
    let mut args = std::env::args().skip(1);
    // Named rather than found on PATH: the cell is handed the server it is
    // meant to use, so a stale copy somewhere else cannot answer instead.
    let binary = args.next().unwrap_or_else(|| "hick-model-rust".to_string());
    let root = args.next().unwrap_or_else(|| ".".to_string());

    let mut model = Model::start(&binary, &root)?;
    let answer = described_types(&mut model)?;

    let mut out = Emit::new();
    out.lines([
        "// Generated by `describegen` from every type marked `#[derive(Describe)]`.",
        "// Do not edit: `examples/rust-generator.hick` owns these bytes, and the",
        "// drift gate fails the build if they stop matching what the generator emits.",
    ])
    .blank();

    for described in answer.types {
        // Rule one: only structs. An enum can carry a `Describe` mark and has
        // no field list, and describing it as if it did would be the model
        // lying rather than the generator failing.
        let DescribedTypesTypesKind::StructDecl(decl) = described else {
            continue;
        };
        // Rule two: the summary is the type's own declaration, read from the
        // model — not a string anybody typed twice.
        let fields: Vec<String> = decl
            .fields
            .iter()
            .map(|field| format!("{}: {}", field.name, field.r#type.text))
            .collect();
        let summary = if fields.is_empty() {
            decl.name.clone()
        } else {
            format!("{} {{ {} }}", decl.name, fields.join(", "))
        };
        // Rule three: the doc comment travels with it, so the generated
        // method reads like the type it describes.
        let doc = decl
            .docs
            .lines()
            .next()
            .filter(|line| !line.is_empty())
            .map(|line| format!("    /// {line}"))
            .unwrap_or_else(|| "    /// Generated from the declaration.".to_string());
        out.lines([
            format!("impl crate::{} {{", decl.name),
            doc,
            "    pub fn describe() -> &'static str {".to_string(),
            format!("        {summary:?}"),
            "    }".to_string(),
            "}".to_string(),
        ])
        .blank();
    }

    print!("{}", out.text());
    Ok(())
}
