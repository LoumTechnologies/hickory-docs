//! Reuse debugger/LSP source coordinates without starting a debugger or executing cells.
use super::*;
use sha2::{Digest, Sha256};
pub(super) fn capture(
    root: &Path,
    record: &Record,
) -> Result<BTreeMap<String, BTreeMap<u32, Value>>> {
    let mut mappings = BTreeMap::<String, BTreeMap<u32, Value>>::new();
    let Some(evidence) = &record.evidence else {
        return Ok(mappings);
    };
    for (doc, hash) in &record.identity.source_hashes {
        if !doc.ends_with(".md") {
            continue;
        }
        let Ok(path) = safe_path(root, doc) else {
            continue;
        };
        let Ok(source) = std::fs::read_to_string(&path) else {
            continue;
        };
        if format!("{:x}", Sha256::digest(source.as_bytes())) != *hash
            || !source.contains("<hick:file")
        {
            continue;
        }
        let Ok(state) = hick_lsp::document::HickDocumentState::from_source(&source) else {
            continue;
        };
        // Map only when the virtual generated bytes match the measured source exactly.
        let matching: Vec<_> = state
            .virtual_files
            .iter()
            .filter_map(|f| {
                let generated = path.parent()?.join(&f.path).canonicalize().ok()?;
                let relative = store::relative(root, &generated);
                let measured = evidence.report.files.get(&relative)?;
                let bytes = std::fs::read(&generated).ok()?;
                (bytes == f.written_content().as_bytes()
                    && record.identity.source_hashes.get(&relative)
                        == Some(&format!("{:x}", Sha256::digest(&bytes))))
                .then_some((
                    relative,
                    generated,
                    measured.lines.keys().copied().collect::<Vec<_>>(),
                ))
            })
            .collect();
        let map = hick_dap::Mapping::for_state(&path, &state, path.parent().unwrap())?;
        for (relative, generated, lines) in matching {
            for line in lines {
                if let Some((source, n)) = map.source_location(&generated, line - 1) {
                    if let Ok(source) = source.canonicalize() {
                        if source.starts_with(root) {
                            mappings.entry(relative.clone()).or_default().insert(
                                line,
                                json!({"path":store::relative(root,&source),"line":n+1}),
                            );
                        }
                    }
                }
            }
        }
    }
    Ok(mappings)
}
