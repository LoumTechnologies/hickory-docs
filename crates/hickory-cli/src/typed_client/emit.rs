fn python(operations: &[Operation], language: &str) -> String {
    let mut out = banner("#", language);
    out.push_str(
        "from __future__ import annotations\n\n\
         from dataclasses import dataclass\n\
         from typing import Any, Literal\n\n\
         from hick_model import Model\n\n\n",
    );
    for op in operations {
        for (name, fields) in &shapes_of(op) {
            out.push_str(&py_class(name, fields));
        }
        out.push_str(&py_class(&format!("{}Result", op.name), &op.result.fields));
        out.push_str(&format!(
            "{}_QUERY = \"\"\"\n{}\n\"\"\"\n\n\n",
            screaming(&op.name),
            op.text
        ));
        let params: Vec<String> = op
            .variables
            .iter()
            .map(|v| format!("{}: Any", v.name))
            .collect();
        let arglist = if params.is_empty() {
            String::new()
        } else {
            format!(", {}", params.join(", "))
        };
        let passthrough: Vec<String> = op
            .variables
            .iter()
            .map(|v| format!("{}={}", v.name, v.name))
            .collect();
        out.push_str(&format!(
            "def {}(model: Model{arglist}) -> {}Result:\n    \
             \"\"\"Ask `{}`, typed.\"\"\"\n    \
             return {}Result._from(model.q({}_QUERY{})._data)\n\n\n",
            snake(&op.name),
            op.name,
            op.name,
            op.name,
            screaming(&op.name),
            if passthrough.is_empty() {
                String::new()
            } else {
                format!(", {}", passthrough.join(", "))
            }
        ));
    }
    out
}

fn py_class(name: &str, fields: &[Field]) -> String {
    let mut out = format!("@dataclass(frozen=True)\nclass {}:\n", pascal(name));
    if fields.is_empty() {
        out.push_str("    pass\n\n\n");
        return out;
    }
    for field in fields {
        if let Some(doc) = &field.description {
            out.push_str(&format!("    # {}\n", doc.lines().next().unwrap_or("")));
        }
        out.push_str(&format!(
            "    {}: {}\n",
            py_name(&field.key),
            py_type(&field.shape)
        ));
    }
    // Python is the only target that needs this. TypeScript's JSON already IS
    // the object, Go decodes into the struct through its tags, and C# through
    // its attributes — but a dataclass is not built from a dict by anything,
    // so without a constructor the annotation is a claim rather than a fact.
    // It stopped being one when a generator read `typename` and the response
    // held `__typename`.
    out.push_str("\n    @staticmethod\n    def _from(data: dict[str, Any]) -> \"");
    out.push_str(&pascal(name));
    out.push_str("\":\n        return ");
    out.push_str(&pascal(name));
    out.push_str("(\n");
    for field in fields {
        // `data[key]` for a field the schema says is always there, and
        // `data.get(key)` only where null is possible. Using `.get` for both
        // types every required field as `Any | None`, which a type checker
        // then rejects against its own declared `str` — twenty-six errors in
        // a generated file, which is worse than no types at all.
        let source = if field.shape.nullable {
            format!("data.get(\"{}\")", field.key)
        } else {
            format!("data[\"{}\"]", field.key)
        };
        out.push_str(&format!(
            "            {}={},\n",
            py_name(&field.key),
            py_build(&field.shape, &source, &format!("_{}", py_name(&field.key)))
        ));
    }
    out.push_str("        )\n\n\n");
    out
}

/// The expression that turns a piece of JSON into this shape.
///
/// `var` names the walrus binding used when the value is optional: a type
/// checker cannot narrow across two separate `data.get(k)` calls, because
/// nothing tells it the two return the same thing. Binding once and testing
/// the binding is the difference between a generated file with no errors and
/// one with an error per optional object.
fn py_build(shape: &Shape, source: &str, var: &str) -> String {
    let build = match &shape.kind {
        Kind::List(item) => format!(
            "[{} for {var}i in ({} or [])]",
            py_build(item, &format!("{var}i"), &format!("{var}j")),
            source
        ),
        Kind::Object(object) => format!("{}._from({source})", pascal(&object.name)),
        Kind::Variants(variants) => {
            // Which class to build is decided by the discriminator, which is
            // why `__typename` has to be in the selection for a variant.
            let arms: Vec<String> = variants
                .iter()
                .map(|v| {
                    let bare = v.name.rsplit('_').next().unwrap_or(&v.name);
                    format!(
                        "{}._from({source}) if ({source} or {{}}).get(\"__typename\") == \"{bare}\"",
                        pascal(&v.name)
                    )
                })
                .collect();
            format!("({} else None)", arms.join(" else "))
        }
        _ => source.to_string(),
    };
    if shape.nullable
        && !matches!(shape.kind, Kind::List(_))
        && !matches!(shape.kind, Kind::Scalar(_) | Kind::Enum { .. })
    {
        // Bind once, then test and use the binding.
        let bound = build.replace(source, var);
        format!("({bound} if ({var} := {source}) is not None else None)")
    } else {
        build
    }
}

/// `__typename` is a dunder in Python and cannot be an attribute name, so it
/// is spelled `typename` — the one place a target language's rules override
/// the response's own spelling, and it is noted rather than silent.
fn py_name(key: &str) -> String {
    if key == "__typename" {
        "typename".to_string()
    } else {
        key.to_string()
    }
}

fn py_type(shape: &Shape) -> String {
    let inner = match &shape.kind {
        Kind::List(item) => format!("list[{}]", py_type(item)),
        Kind::Scalar(name) => match name.as_str() {
            "String" | "ID" => "str".into(),
            "Int" => "int".into(),
            "Float" => "float".into(),
            "Boolean" => "bool".into(),
            _ => "Any".into(),
        },
        Kind::Enum { values, .. } => format!(
            "Literal[{}]",
            values
                .iter()
                .map(|v| format!("\"{v}\""))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Kind::Object(object) => pascal(&object.name),
        Kind::Variants(variants) => variants
            .iter()
            .map(|v| pascal(&v.name))
            .collect::<Vec<_>>()
            .join(" | "),
    };
    if shape.nullable {
        format!("{inner} | None")
    } else {
        inner
    }
}

