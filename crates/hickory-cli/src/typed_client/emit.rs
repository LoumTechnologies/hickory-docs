fn typescript(operations: &[Operation], language: &str) -> String {
    let mut out = banner("//", language);
    out.push_str("import type { Model } from \"./hick_model\";\n\n");
    for op in operations {
        for (name, fields) in &shapes_of(op) {
            out.push_str(&ts_interface(name, fields));
        }
        out.push_str(&ts_interface(
            &format!("{}Result", op.name),
            &op.result.fields,
        ));
        out.push_str(&format!(
            "export const {}_QUERY = `\n{}\n`;\n\n",
            screaming(&op.name),
            op.text
        ));
        let params: Vec<String> = op
            .variables
            .iter()
            .map(|v| format!("{}: unknown", v.name))
            .collect();
        out.push_str(&format!(
            "/** Ask `{}`, typed. */\nexport function {}(model: Model{}): Promise<{}Result> {{\n  \
             return model.q({}_QUERY{}) as Promise<{}Result>;\n}}\n\n",
            op.name,
            camel(&op.name),
            if params.is_empty() {
                String::new()
            } else {
                format!(", {}", params.join(", "))
            },
            op.name,
            screaming(&op.name),
            if op.variables.is_empty() {
                String::new()
            } else {
                format!(
                    ", {{ {} }}",
                    op.variables
                        .iter()
                        .map(|v| v.name.clone())
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            },
            op.name
        ));
    }
    out
}

fn ts_interface(name: &str, fields: &[Field]) -> String {
    let mut out = format!("export interface {} {{\n", pascal(name));
    for field in fields {
        if let Some(doc) = &field.description {
            out.push_str(&format!("  /** {} */\n", doc.lines().next().unwrap_or("")));
        }
        out.push_str(&format!(
            "  {}: {};\n",
            quote_key(&field.key),
            ts_type(&field.shape)
        ));
    }
    out.push_str("}\n\n");
    out
}

fn quote_key(key: &str) -> String {
    if key.starts_with("__") {
        format!("\"{key}\"")
    } else {
        key.to_string()
    }
}

fn ts_type(shape: &Shape) -> String {
    let inner = match &shape.kind {
        Kind::List(item) => format!("Array<{}>", ts_type(item)),
        Kind::Scalar(name) => match name.as_str() {
            "String" | "ID" => "string".into(),
            "Int" | "Float" => "number".into(),
            "Boolean" => "boolean".into(),
            _ => "unknown".into(),
        },
        Kind::Enum { values, .. } => values
            .iter()
            .map(|v| format!("\"{v}\""))
            .collect::<Vec<_>>()
            .join(" | "),
        Kind::Object(object) => pascal(&object.name),
        Kind::Variants(variants) => variants
            .iter()
            .map(|v| pascal(&v.name))
            .collect::<Vec<_>>()
            .join(" | "),
    };
    if shape.nullable {
        format!("{inner} | null")
    } else {
        inner
    }
}

