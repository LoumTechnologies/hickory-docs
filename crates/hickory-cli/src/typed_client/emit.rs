fn typescript(operations: &[Operation], language: &str) -> String {
    let mut out = banner("//", language);
    out.push_str("import type { Model } from \"./hick_model\";\n\n");
    for op in operations {
        for (name, fields) in &shapes_of(op) {
            out.push_str(&ts_interface(name, fields));
        }
        out.push_str(&ts_interface(
            &format!("{}Result", op.name),
            &op.result.fields,
        ));
        out.push_str(&format!(
            "export const {}_QUERY = `\n{}\n`;\n\n",
            screaming(&op.name),
            op.text
        ));
        let params: Vec<String> = op
            .variables
            .iter()
            .map(|v| format!("{}: unknown", v.name))
            .collect();
        out.push_str(&format!(
            "/** Ask `{}`, typed. */\nexport function {}(model: Model{}): Promise<{}Result> {{\n  \
             return model.q({}_QUERY{}) as Promise<{}Result>;\n}}\n\n",
            op.name,
            camel(&op.name),
            if params.is_empty() {
                String::new()
            } else {
                format!(", {}", params.join(", "))
            },
            op.name,
            screaming(&op.name),
            if op.variables.is_empty() {
                String::new()
            } else {
                format!(
                    ", {{ {} }}",
                    op.variables
                        .iter()
                        .map(|v| v.name.clone())
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            },
            op.name
        ));
    }
    out
}

fn ts_interface(name: &str, fields: &[Field]) -> String {
    let mut out = format!("export interface {} {{\n", pascal(name));
    for field in fields {
        if let Some(doc) = &field.description {
            out.push_str(&format!("  /** {} */\n", doc.lines().next().unwrap_or("")));
        }
        out.push_str(&format!(
            "  {}: {};\n",
            quote_key(&field.key),
            ts_type(&field.shape)
        ));
    }
    out.push_str("}\n\n");
    out
}

fn quote_key(key: &str) -> String {
    if key.starts_with("__") {
        format!("\"{key}\"")
    } else {
        key.to_string()
    }
}

fn ts_type(shape: &Shape) -> String {
    let inner = match &shape.kind {
        Kind::List(item) => format!("Array<{}>", ts_type(item)),
        Kind::Scalar(name) => match name.as_str() {
            "String" | "ID" => "string".into(),
            "Int" | "Float" => "number".into(),
            "Boolean" => "boolean".into(),
            _ => "unknown".into(),
        },
        Kind::Enum { values, .. } => values
            .iter()
            .map(|v| format!("\"{v}\""))
            .collect::<Vec<_>>()
            .join(" | "),
        Kind::Object(object) => pascal(&object.name),
        Kind::Variants(variants) => variants
            .iter()
            .map(|v| pascal(&v.name))
            .collect::<Vec<_>>()
            .join(" | "),
    };
    if shape.nullable {
        format!("{inner} | null")
    } else {
        inner
    }
}

// ---------------------------------------------------------------------------
// Go
// ---------------------------------------------------------------------------

fn go(operations: &[Operation], language: &str) -> String {
    let mut out = banner("//", language);
    out.push_str("package model\n\n");
    for op in operations {
        for (name, fields) in &shapes_of(op) {
            out.push_str(&go_struct(name, fields));
        }
        out.push_str(&go_struct(&format!("{}Result", op.name), &op.result.fields));
        out.push_str(&format!(
            "const {}Query = `\n{}\n`\n\n",
            pascal(&op.name),
            op.text
        ));
    }
    out
}

fn go_struct(name: &str, fields: &[Field]) -> String {
    let mut out = format!("type {} struct {{\n", pascal(name));
    for field in fields {
        if let Some(doc) = &field.description {
            out.push_str(&format!("\t// {}\n", doc.lines().next().unwrap_or("")));
        }
        // The json tag is not decoration here: Go's exported-by-capitalisation
        // means every field is renamed on the way in, and without the tag the
        // decoder silently leaves it zero.
        out.push_str(&format!(
            "\t{} {} `json:\"{}\"`\n",
            pascal(&field.key.replace("__", "")),
            go_type(&field.shape),
            field.key
        ));
    }
    out.push_str("}\n\n");
    out
}

fn go_type(shape: &Shape) -> String {
    let inner = match &shape.kind {
        Kind::List(item) => format!("[]{}", go_type(item)),
        Kind::Scalar(name) => match name.as_str() {
            "String" | "ID" => "string".into(),
            "Int" => "int".into(),
            "Float" => "float64".into(),
            "Boolean" => "bool".into(),
            _ => "any".into(),
        },
        // Go has no union type, so a variant selection is the widest struct
        // with the discriminator kept. Named rather than silently flattened:
        // the caller switches on Typename, which is what they would do in Go
        // anyway.
        Kind::Enum { .. } => "string".into(),
        Kind::Object(object) => pascal(&object.name),
        Kind::Variants(_) => "map[string]any".into(),
    };
    // A pointer only where a null is possible AND the zero value would lie.
    if shape.nullable && !inner.starts_with("[]") && !inner.starts_with("map[") {
        format!("*{inner}")
    } else {
        inner
    }
}

// ---------------------------------------------------------------------------
// Names
// ---------------------------------------------------------------------------

fn pascal(name: &str) -> String {
    name.split(['_', '-'])
        .filter(|p| !p.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn camel(name: &str) -> String {
    let p = pascal(name);
    let mut chars = p.chars();
    match chars.next() {
        Some(first) => first.to_lowercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.extend(ch.to_lowercase());
    }
    out
}

fn screaming(name: &str) -> String {
    snake(name).to_uppercase()
}
