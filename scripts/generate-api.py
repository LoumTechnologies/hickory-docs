#!/usr/bin/env python3
"""Generate the mechanical API adapters through the TypeScript code model."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / 'code-models/clients/python'))
from hick_model import Model

PAGE = ROOT / '.hickory-source/mechanisms/apps/web/src/api/generatedApi.ts.md'
OUTPUT = ROOT / 'apps/web/src/api/generatedApi.ts'
QUERY = '''{ types(moduleIs: "../routes.ts") { name methods {
  name parameters { name isOptional hasDefault isRest }
  returnType { text typeArguments { isLiteral literalValue } }
  declaration { startLine }
} } unresolved { message } }'''


def generate():
    with Model(str(ROOT / 'code-models/typescript/hick-model-typescript'),
               str(ROOT / 'apps/web/src/api/route-model')) as model:
        data = model.q(QUERY)
    if data.unresolved:
        raise ValueError('Unresolved route types: ' + str([item.message for item in data.unresolved]))
    routes, = [item for item in data.types if item.name == 'ApiRoutes']
    source = (ROOT / 'apps/web/src/api/routes.ts').read_text().splitlines()
    lines = ['// Generated by scripts/generate-api.py; edit the literate route declarations.',
             'import type { ApiRoutes } from "./routes";',
             'import type { request as Request } from "./client";',
             'type Response<K extends keyof ApiRoutes> = ReturnType<ApiRoutes[K]>["response"];',
             'export function generatedApi(request: typeof Request) { return {']
    for method in routes.methods:
        name = method.name
        verb = method.returnType.text.split('<')[0]
        args = method.returnType.typeArguments
        if verb not in ('GET', 'POST', 'PUT', 'DELETE') or len(args) != 3 or not all(args[i].isLiteral for i in (0, 2)):
            raise ValueError('Unsupported route metadata: ' + name)
        path, body = args[0].literalValue, args[2].literalValue
        params = method.parameters
        names = [p.name for p in params]
        if any(p.isRest or p.hasDefault for p in params):
            raise ValueError('Rest/default parameters need an explicit adapter: ' + name)
        used, pieces, cursor = [], [], 0
        for match in re.finditer(r'\{(\w+)(:url)?\}', path):
            param, encoded = match.groups()
            if param not in names:
                raise ValueError('Unknown path parameter: ' + param)
            used.append(param)
            pieces.extend([json.dumps(path[cursor:match.start()]), 'encodeURIComponent(' + param + ')' if encoded else param])
            cursor = match.end()
        pieces.append(json.dumps(path[cursor:]))
        remaining = [p for p in names if p not in used]
        if body == '$fields':
            payload = '{ ' + ', '.join(remaining) + ' }' if remaining else None
        elif body == '$empty' and not remaining:
            payload = '{}'
        elif remaining == [body]:
            payload = body
        else:
            raise ValueError('Direct body must name the sole remaining parameter: ' + name)
        if verb == 'GET' and payload is not None:
            raise ValueError('GET cannot carry a body: ' + name)
        signature = ', '.join(f'{p.name}{"?" if p.isOptional else ""}: Parameters<ApiRoutes[{json.dumps(name)}]>[{i}]' for i, p in enumerate(params))
        start = method.declaration.startLine - 1
        first = start
        while first and source[first - 1].lstrip().startswith(('/**', '*', '//')):
            first -= 1
        lines.extend(source[first:start])
        lines.append(f'  {name}: ({signature}) => request<Response<{json.dumps(name)}>>({json.dumps(verb)}, ' + ' + '.join(pieces) + (', ' + payload if payload is not None else '') + '),')
    return '\n'.join(lines + ['}; }'])


def recording(code):
    inputs = hashlib.sha256()
    for path in ('scripts/generate-api.py', 'apps/web/src/api/routes.ts', 'apps/web/src/api/route-model/tsconfig.json'):
        inputs.update(path.encode() + b'\0' + (ROOT / path).read_bytes() + b'\0')
    command = 'python3 scripts/generate-api.py --emit --inputs ' + inputs.hexdigest()
    image = 'host-toolchain'
    key = hashlib.sha256(('image:' + image + '\ncaps:\ncmd:' + command + '\ninputs:' + hashlib.sha256(b'inputs-v1:').hexdigest()).encode()).hexdigest()
    digest = hashlib.sha256(code.encode()).hexdigest()
    return (f'<api:file path="apps/web/src/api/generatedApi.ts"><api:exec container="api-codegen" image="{image}" show="output">\n'
            f'<api:cmd>{command}</api:cmd>\n<api:ingested key="{key}" sha256="{digest}">\n{code}</api:ingested>\n</api:exec></api:file>')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    for flag in ('check', 'write', 'emit'):
        mode.add_argument('--' + flag, action='store_true')
    parser.add_argument('--inputs')
    args = parser.parse_args()
    code = generate()
    block = recording(code)
    if args.emit:
        if args.inputs != block.split('--inputs ')[1].split('<')[0]:
            raise ValueError('Recorded generator inputs have changed; regenerate first')
        print(code, end='')
        return
    page = PAGE.read_text()
    updated, count = re.subn(r'(?s)([<]!-- api-codegen:start -->\n).*?(\n[<]!-- api-codegen:end -->)', lambda m: m[1] + block + m[2], page)
    if count != 1:
        raise ValueError('Expected one retained-output block')
    if args.write:
        PAGE.write_text(updated)
    elif updated != page or not OUTPUT.is_file() or OUTPUT.read_bytes() != (code + '\n').encode():
        raise ValueError('API adapters are stale; follow the literate API generation workflow')
    print('API adapters: ' + ('recording updated; run literate-generate' if args.write else 'model, recording and output agree'))


if __name__ == '__main__':
    main()
